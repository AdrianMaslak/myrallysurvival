"""Write the countryside stages' routes into the game source (docs/STAGES.md).

Reads Art/Maps/Countryside/Export/countryside.json (written by the map builder) and writes
Source/RallySurvival/Private/Game/CountrysideStages.inl: each special stage's id, name, surface, road width
and its centre line sampled about every 3 m from the start gate to the finish gate (Unreal frame, metres).
Run after the map's routes change: python scripts/export_stage_routes.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Art/Maps/Countryside/Export/countryside.json"
TARGET = ROOT / "Source/RallySurvival/Private/Game/CountrysideStages.inl"

data = json.loads(SOURCE.read_text(encoding="utf-8"))
routes = {r["id"]: r for r in data["routes"]}
lines = [
    "// Generated by scripts/export_stage_routes.py from Art/Maps/Countryside/Export/countryside.json. Do not edit.",
    "// Special stages of the Lipova countryside map: id, name, surface, road width (m) and centre line (m, Unreal frame).",
]
for stage in data["stages"]:
    route = routes[stage["id"]]
    points = ", ".join(f"{{{p[0]:.2f}, {p[1]:.2f}, {p[2]:.2f}}}" for p in route["samples"])
    name = stage["id"].replace("-", "_")
    lines.append(f"static const double {name}_Points[][3] = {{ {points} }};")
lines.append("static const FRallyStageSource CountrysideStages[] = {")
for stage in data["stages"]:
    name = stage["id"].replace("-", "_")
    lines.append(f'    {{ TEXT("{stage["id"]}"), TEXT("{stage["name"]}"), TEXT("{stage["surface"]}"), {routes[stage["id"]]["width"]:.1f}, '
                 f"{name}_Points, UE_ARRAY_COUNT({name}_Points) }},")
lines.append("};")
TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"STAGE_ROUTES {len(data['stages'])} stages, {sum(len(routes[s['id']]['samples']) for s in data['stages'])} points -> {TARGET}")

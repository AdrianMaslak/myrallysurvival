ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'Art/Maps/Highlands'


def length(points):
    return sum(math.dist(a, b) for a, b in zip(points, points[1:]))


def resample(points, spacing=2.0):
    distances = [0.0]
    for a, b in zip(points, points[1:]):
        distances.append(distances[-1] + math.dist(a, b))
    count = math.ceil(distances[-1] / spacing)
    result = []
    j = 1
    for i in range(count + 1):
        d = distances[-1] * i / count
        while j < len(points)-1 and distances[j] < d:
            j += 1
        t = (d-distances[j-1]) / (distances[j]-distances[j-1])
        result.append([a+(b-a)*t for a, b in zip(points[j-1], points[j])])
    return result


def fit(points, target, origin):
    lo, hi = .1, 10.
    for _ in range(45):
        scale = (lo+hi)/2
        p = [[x*scale, y*scale, z] for x, y, z in points]
        if length(p) < target: lo = scale
        else: hi = scale
    p = resample([[origin[0]+x*scale, origin[1]+y*scale, origin[2]+z] for x, y, z in points])
    # Resampling corners loses millimetres. Correct horizontal scale once more.
    for _ in range(3):
        k = target/length(p)
        p = [[origin[0]+(x-origin[0])*k, origin[1]+(y-origin[1])*k, z] for x,y,z in p]
    return p


def create():
    n = 6000
    mud = []
    gravel = []
    for i in range(n+1):
        t = i/n
        fade = math.sin(math.pi*t)**2
        mud.append([4200*t, fade*(210*math.sin(6*math.pi*t)+65*math.sin(18*math.pi*t)),
                    80*(3*t*t-2*t*t*t)+25*fade*math.sin(4*math.pi*t)])
        gravel.append([fade*(250*math.sin(8*math.pi*t)+65*math.sin(20*math.pi*t)), 4200*t,
                       80*(3*t*t-2*t*t*t)+65*fade*math.sin(4*math.pi*t)])
    a = fit(mud, 6000, [100,0,0])
    b = fit(gravel, 7000, [a[-1][0], a[-1][1]+180, a[-1][2]])
    # Six traverses joined by five genuine 180-degree bends.
    raw = []
    for leg in range(6):
        for i in range(1001):
            t = i/1000
            x = -1100*t if leg%2 == 0 else -1100+1100*t
            raw.append([x, -90*leg])
        if leg < 5:
            cx = -1100 if leg%2 == 0 else 0
            for i in range(1,181):
                angle = math.pi*i/180
                raw.append([cx + (-1 if leg%2 == 0 else 1)*45*math.sin(angle),
                            -90*leg-45+45*math.cos(angle)])
    road = []
    for i,(x,y) in enumerate(raw):
        t = i/(len(raw)-1)
        road.append([x,y,40*(3*t*t-2*t*t*t)+190*math.sin(math.pi*t)**2])
    c = fit(road, 7000, [b[-1][0]-180,b[-1][1],b[-1][2]])
    stages = [dict(id='SS1',name='Blackwater Mud',surface='Mud',width=6.4,samples=a),
              dict(id='SS2',name='Pine Ridge Gravel',surface='Gravel',width=6.2,samples=b),
              dict(id='SS3',name='High Pass Hairpins',surface='Tarmac',width=6.6,samples=c)]
    links = [dict(id='Start',surface='Gravel',width=12.,samples=resample([[0,0,0],a[0]])),
             dict(id='Service1',surface='Gravel',width=12.,samples=resample([a[-1],b[0]])),
             dict(id='Service2',surface='Gravel',width=12.,samples=resample([b[-1],c[0]]))]
    stats = []
    for stage,target in zip(stages,[6000,7000,7000]):
        p=stage['samples']; d=length(p)
        grade=max(abs(b[2]-a[2])/math.hypot(b[0]-a[0],b[1]-a[1]) for a,b in zip(p,p[1:]))
        assert abs(d-target)<.01, (stage['id'],d)
        assert grade<.16, (stage['id'],grade)
        stats.append(dict(id=stage['id'],length_m=d,max_grade=grade,
                          ascent_m=sum(max(0,b[2]-a[2]) for a,b in zip(p,p[1:])),
                          descent_m=sum(max(0,a[2]-b[2]) for a,b in zip(p,p[1:]))))
    allp=[p for r in stages+links for p in r['samples']]
    assert all(-700<x<7200 and -700<y<7200 for x,y,z in allp)
    services=[[sum(p[k] for p in (r['samples'][0],r['samples'][-1]))/2 for k in range(3)] for r in links[1:]]
    return dict(map='/Game/Maps/Highlands/L_Highlands',stages=stages,links=links,
                services=services,stats=stats,landscape=dict(size=1009,spacing=8,origin=[-800,-800,200],z_scale=200))


